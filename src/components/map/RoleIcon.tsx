/**
 * Icon of a device role. roles.json names the icon; this file maps the name to a drawing.
 * An unknown name falls back to a neutral box, so new data never breaks the map.
 */
import {
  Activity,
  Archive,
  AudioWaveform,
  BatteryCharging,
  Bone,
  Box,
  BrickWall,
  Cable,
  Cloud,
  CreditCard,
  Database,
  DoorOpen,
  FlaskConical,
  FolderOpen,
  Globe,
  Headset,
  Images,
  KeyRound,
  Landmark,
  Laptop,
  Monitor,
  Network,
  Phone,
  Plug,
  Printer,
  RadioTower,
  Receipt,
  Server,
  Smartphone,
  Split,
  SquareTerminal,
  Tag,
  Wifi,
  type LucideIcon,
} from 'lucide-react';

const ICONS: Record<string, LucideIcon> = {
  plug: Plug,
  battery: BatteryCharging,
  firewall: BrickWall,
  switch: Network,
  wifi: Wifi,
  server: Server,
  storage: Database,
  archive: Archive,
  desktop: Monitor,
  laptop: Laptop,
  card: CreditCard,
  receipt: Receipt,
  label: Tag,
  printer: Printer,
  phone: Phone,
  xray: Bone,
  lab: FlaskConical,
  ultrasound: AudioWaveform,
  smartphone: Smartphone,
  vm: Box,
  key: KeyRound,
  images: Images,
  folder: FolderOpen,
  door: DoorOpen,
  activity: Activity,
  terminal: SquareTerminal,
  cable: Cable,
  tower: RadioTower,
  globe: Globe,
  bank: Landmark,
  headset: Headset,
  split: Split,
  cloud: Cloud,
};

export function RoleIcon({ icon, className }: { icon: string | undefined; className?: string }) {
  const Icon = (icon && ICONS[icon]) || Box;
  return <Icon className={className} aria-hidden="true" />;
}
